#!/usr/bin/env node
// Builds docs/compatibility.md from the saved probe results (docs/probe-results/*.json) and the rules table.
//   npm run build && node scripts/compat-table.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolveTarget } from "../dist/index.js";

const dir = "docs/probe-results";
const runs = readdirSync(dir).filter((f) => f.endsWith(".json")).sort().map((f) => ({ file: f, ...JSON.parse(readFileSync(`${dir}/${f}`, "utf8")) }));
const results = runs.flatMap((r) => r.results.map((x) => ({ ...x, date: r.date })));
// Later files win, so a recheck after a fix replaces the earlier result.
const live = (model, part, probe) => results.findLast((r) => r.model === model && r.part === part && r.probe === probe);

// What the rules table does with a keyword, for targets that haven't been probed live.
const PROBE_VALUES = { "pattern (lookahead)": ["pattern", "^(?=a)a+$"], "pattern (\\p{L} escape)": ["pattern", "^\\p{L}+$"] };
function docsVerdict(target, keyword) {
  const caps = resolveTarget(target);
  if (caps.keywords === "any" || keyword === "baseline") return "kept";
  if (keyword in PROBE_VALUES) {
    const [k, v] = PROBE_VALUES[keyword];
    return caps.keywords.includes(k) && (!caps.rules?.[k] || caps.rules[k](v)) ? "kept" : "rewritten";
  }
  const allow = new Set(caps.keywords);
  const special = {
    "type array (null)": caps.typeArrays,
    "$ref sibling description": caps.refSiblings,
    recursion: caps.recursion,
    "root anyOf": !caps.rootObject,
    "optional field": !caps.allRequired,
    "open object": !caps.closedObjects,
    "empty schema": caps.openSchemas,
    "format: uri": allow.has("format") && (caps.formats === "any" || caps.formats.includes("uri")),
    "minItems: 2": allow.has("minItems") && (!caps.rules?.minItems || caps.rules.minItems(2)),
  };
  const ok = keyword in special ? special[keyword] : allow.has(keyword.split(" ")[0]);
  return ok ? "kept" : "rewritten";
}

const geminiModel = "google/gemini-3.5-flash-lite";
const keywordRows = [...new Map(results.filter((r) => r.model === geminiModel && r.part === "keyword").map((r) => [r.probe, live(r.model, r.part, r.probe)])).values()];
const corpusNames = [...new Set(results.filter((r) => r.part === "converted").map((r) => r.probe))];
const mark = (r) => (!r ? "–" : r.accepted ? "✅ accepted" : "❌ rejected");

const md = `# Compatibility

What each target accepts, and what llm-json-schema does about it. Generated by \`scripts/compat-table.mjs\` from the
probe results in [\`docs/probe-results/\`](probe-results/). Don't edit by hand.

- **Live:** sent to the real API by \`npm run probe\`. ✅ means the API accepted the schema; it doesn't prove the model enforces
  the keyword, so \`check()\` still validates output against your original schema.
- **Docs:** from the provider's documentation, not yet probed. "kept" means llm-json-schema sends the keyword as written;
  "rewritten" means it's changed or moved to the description (see \`losses\`).

## Keywords

| Keyword | Gemini JSON Schema fields (live, ${keywordRows[0]?.date ?? "–"}) | OpenAI strict (docs) | Anthropic strict (docs) |
|---|---|---|---|
${keywordRows.map((r) => `| ${r.probe.replace(/\|/g, "\\|")} | ${mark(r)} | ${docsVerdict("openai", r.probe)} | ${docsVerdict("anthropic", r.probe)} |`).join("\n")}

## Real-world schemas, after conversion (live)

Each schema is a shape from a public bug report or common schema-library output (see \`test/corpus.mjs\`), converted for the
target and sent to the API.

| Schema | \`google\` (JSON Schema fields) | \`google-openapi\` (OpenAPI Schema) |
|---|---|---|
${corpusNames.map((n) => `| ${n} | ${mark(live(geminiModel, "converted", n))} | ${mark(live("google-openapi/gemini-3.5-flash-lite", "converted", n)) === "–" ? "skipped: recursive" : mark(live("google-openapi/gemini-3.5-flash-lite", "converted", n))} |`).join("\n")}

${runs.map((r) => (r.note ? `**Note on ${r.file}:** ${r.note}` : "")).filter(Boolean).join("\n\n")}

## Not probed yet

OpenAI and Anthropic haven't been probed live. Their rules come from the documentation (checked 2026-11-02), and where
the docs say nothing about a keyword it's treated as unsupported. To add them, run \`npm run probe\` with
\`OPENAI_API_KEY\` / \`ANTHROPIC_API_KEY\`, save the JSON from \`probe-results/\` into \`docs/probe-results/\`, and rerun this
script.
`;

writeFileSync("docs/compatibility.md", md);
console.log(`docs/compatibility.md: ${keywordRows.length} keywords, ${corpusNames.length} schemas`);
